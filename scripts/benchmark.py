"""Train GCN and MLP with 10 seeds and run label propagation on all three datasets.

Writes results/accuracy.csv (one row per run) and RESULTS.md (the summary table).
"""

from __future__ import annotations

import csv
import platform
import statistics
import time
from pathlib import Path

import numpy as np
import torch
from scipy import sparse
from scipy.sparse import csgraph

from gcn import label_propagation, load, normalized_adjacency, train
from gcn.data import DATASETS

ROOT = Path(__file__).resolve().parents[1]
SEEDS = range(10)
NAMES = {"cora": "Cora", "citeseer": "CiteSeer", "pubmed": "PubMed"}
METHODS = {
    "gcn": "GCN",
    "mlp": "MLP",
    "label_propagation": "Label propagation",
    "label_propagation_plain": "Label propagation, no class mass normalisation",
}
# Kipf and Welling (2017), Table 2. LP numbers there are quoted from Yang et al. (2016).
PAPER = {
    "gcn": {"cora": 81.5, "citeseer": 70.3, "pubmed": 79.0},
    "label_propagation": {"cora": 68.0, "citeseer": 45.3, "pubmed": 63.0},
}


def main() -> None:
    torch.set_num_threads(2)
    rows = []
    unreachable = {}
    start = time.time()
    for name in DATASETS:
        graph = load(name)
        unreachable[name] = test_nodes_without_training_node(graph)
        adj = normalized_adjacency(graph.edges, graph.num_nodes)
        for method in ("gcn", "mlp"):
            for seed in SEEDS:
                _, result = train(graph, method, seed, adj=adj)
                rows.append(result)
                print(f"{name:9s} {method:4s} seed {seed}: {100 * result.test_acc:.1f}", flush=True)
        for class_mass in (True, False):
            result = label_propagation(graph, class_mass=class_mass)
            rows.append(result)
            print(f"{name:9s} {result.method}: {100 * result.test_acc:.1f}", flush=True)
    minutes = (time.time() - start) / 60

    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    with open(out / "accuracy.csv", "w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["dataset", "method", "seed", "test_acc", "val_acc", "epochs"])
        for r in rows:
            writer.writerow(
                [r.dataset, r.method, r.seed, f"{r.test_acc:.4f}", f"{r.val_acc:.4f}", r.epochs]
            )
    write_report(rows, minutes, unreachable)


def test_nodes_without_training_node(graph) -> int:
    """Test nodes in connected components that contain no training node."""
    src, dst = graph.edges.numpy()
    n = graph.num_nodes
    adj = sparse.csr_matrix((np.ones(len(src)), (src, dst)), shape=(n, n))
    _, component = csgraph.connected_components(adj, directed=False)
    reachable = np.isin(component, component[graph.train.numpy()])
    return int((~reachable[graph.test.numpy()]).sum())


def cell(values: list[float]) -> str:
    if len(values) == 1:
        return f"{values[0]:.1f}"
    return f"{statistics.mean(values):.1f} ± {statistics.stdev(values):.1f}"


def write_report(rows, minutes: float, unreachable: dict[str, int]) -> None:
    lines = [
        "# Results",
        "",
        "Test accuracy (%) on the public Planetoid splits. GCN and MLP: mean ± sample",
        f"standard deviation over {len(SEEDS)} seeds. Label propagation is deterministic.",
        "Paper values are from Kipf and Welling (2017), Table 2 (their LP row quotes",
        "Yang et al., 2016). Generated by `scripts/benchmark.py`; per-run numbers are",
        "in `results/accuracy.csv`.",
        "",
        "| Method | " + " | ".join(NAMES[d] for d in DATASETS) + " |",
        "|---|" + "---:|" * len(DATASETS),
    ]
    for method, label in METHODS.items():
        cells = []
        for d in DATASETS:
            accs = [100 * r.test_acc for r in rows if r.method == method and r.dataset == d]
            cells.append(cell(accs))
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
        if method in PAPER:
            paper = " | ".join(f"{PAPER[method][d]:.1f}" for d in DATASETS)
            lines.append(f"| {label} (paper) | {paper} |")

    epochs = {d: [r.epochs for r in rows if r.method == "gcn" and r.dataset == d] for d in DATASETS}
    lines += [
        "",
        "GCN epochs before early stopping: "
        + ", ".join(f"{NAMES[d]} {min(e)}–{max(e)}" for d, e in epochs.items())
        + ".",
        "Test nodes with no path to any training node (label propagation cannot reach them): "
        + ", ".join(f"{NAMES[d]} {unreachable[d]}" for d in DATASETS)
        + ".",
        "",
        f"Wall time for the whole table: {minutes:.1f} min on {platform.machine()} CPU, "
        f"2 threads, torch {torch.__version__}.",
        "",
    ]
    (ROOT / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
